function clone(x){return JSON.parse(JSON.stringify(x))}
function read(key,fallback){const raw=localStorage.getItem(key);return raw?JSON.parse(raw):clone(fallback)}
function normalizeBindings(raw){
 const out={};
 Object.entries(raw||{}).forEach(([key,values])=>{
  const code=key.replace(/^(REPORT\||report:)/,'');
  if(!Array.isArray(values))return;
  out[code]=[...new Set([...(out[code]||[]),...values.filter(v=>typeof v==='string')])];
 });
 return out;
}
function sourceKey(r){return [r.type,r.type==='briefing'?r.subtype||'':'',r.type==='report'?'report:'+r.sendCode:r.sourceId||r.id].join('|')}
function rowKey(r){return sourceKey(r)+'|'+r.componentId}
function reportRows(bindings,rows,overrides={}){
 const out=rows.filter(r=>r.type!=='report');
 Object.entries(bindings).forEach(([code,names])=>{
  const existing=rows.filter(r=>r.type==='report'&&r.sendCode===code);
  const original=existing[0]||catalog.find(r=>r.sendCode===code);
  if(!original)return;const data={...original,...overrides[code]};
  names.forEach(name=>{const c=components.find(c=>c[0]===name||c[1]===name);if(!c)return;
   const old=existing.find(r=>r.componentId===c[0]);
   out.push({...data,...old,type:'report',sourceId:'report:'+code,componentId:c[0],compName:c[1],x:c[2],y:c[3],
    title:code+' · '+data.materialName,checkTime:data.sendDate||'',bimModel:old?.bimModel||data.bimModel||'XA000_ZMXA_A_建筑单体主文件-01地块-地上.rvt'});
  });
 });
 return out;
}
function baseline(){return{records:reportRows(seedBindings,[]),reportBindings:clone(seedBindings)}}
function load(){
 const state=read(KEY,{records:[],reportBindings:null});
 const bindings={...clone(seedBindings),...normalizeBindings(state.reportBindings||read(LEGACY,{}))};
 return{records:reportRows(bindings,Array.isArray(state.records)?state.records:[],state.reportOverrides||{}),reportBindings:bindings,reportOverrides:state.reportOverrides||{}};
}
function save(rows,options={}){
 const state=load(),incoming=(rows||[]).filter(r=>r&&['briefing','measure','report'].includes(r.type)&&r.sourceId&&r.componentId);
 const replacing=new Set(options.replaceSources||[]),map=new Map(state.records.filter(r=>!replacing.has(sourceKey(r))).map(r=>[rowKey(r),r]));
 incoming.forEach(r=>map.set(rowKey(r),clone(r)));
 const bindings={...state.reportBindings};
 incoming.filter(r=>r.type==='report').forEach(r=>{
  if(!bindings[r.sendCode])bindings[r.sendCode]=[];
  const c=components.find(c=>c[0]===r.componentId);
  if(c&&!bindings[r.sendCode].includes(c[1]))bindings[r.sendCode].push(c[1]);
 });
 Object.entries(normalizeBindings(options.reportBindings)).forEach(([code,names])=>bindings[code]=names);
 const overrides={...state.reportOverrides,...options.reportOverrides};
 const next={records:reportRows(bindings,[...map.values()],overrides),reportBindings:bindings,reportOverrides:overrides};
 localStorage.setItem(KEY,JSON.stringify(next));
 // 新数据以同一个存储项提交；旧索引仅供旧版本页面兼容读取。
 try{localStorage.setItem(LEGACY,JSON.stringify(bindings))}catch{}
 return next;
}
function status(r){if(r.issueRequired===false)return'无需整改';const raw=String(r.baseStatus||r.status||r.state||'待整改');return(raw==='逾期未整改'||raw==='待整改逾期')?'待整改':raw}
function overdueDays(r){
 const s=status(r);if(s==='无需整改'||!/^\d{4}-\d{2}-\d{2}$/.test(r.deadline||''))return 0;
 const end=['待整改','继续整改'].includes(s)?new Date().toLocaleDateString('sv-SE'):(r.rectifiedAt||r.reviewAt||'').slice(0,10);
 if(!end)return 0;const days=(Date.parse(end+'T00:00:00Z')-Date.parse(r.deadline+'T00:00:00Z'))/86400000;
 return Number.isFinite(days)?Math.max(0,Math.round(days)):0;
}
